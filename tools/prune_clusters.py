#!/usr/bin/env python3
"""Copies the generated cluster code, only the clusters in the keep list.

rs-matter-codegen writes clusters_generated.rs (the globals and one `pub mod <cluster>` per
cluster, each an include! of OUT_DIR/clusters_generated/<cluster>.rs) and the cluster files.
Here the modules not kept are dropped from the root and the includes point next to it.

Usage: prune_clusters.py <generated dir> <destination dir> <clusters.txt>
"""

import os
import re
import shutil
import sys

src, dst, keep_file = sys.argv[1:4]
keep = {l.strip() for l in open(keep_file) if l.strip() and not l.startswith("#")}

root = open(os.path.join(src, "clusters_generated.rs")).read()
block = re.compile(
    r'/// Generated cluster module\n(?:#\[[^\n]*\]\n)*pub mod (\w+) \{\n'
    r'\s*include!\(concat!\(env!\("OUT_DIR"\), "/clusters_generated/\w+\.rs"\)\);\n\}\n\n')
found = set()


def replace(m):
    name = m.group(1)
    found.add(name)
    if name not in keep:
        return ""
    return m.group(0).replace(
        f'include!(concat!(env!("OUT_DIR"), "/clusters_generated/{name}.rs"));',
        f'include!("clusters_generated/{name}.rs");')


root = block.sub(replace, root)
missing = keep - found
if missing:
    sys.exit(f"clusters.txt names clusters the generator does not have: {sorted(missing)}")

shutil.rmtree(os.path.join(dst, "clusters_generated"), ignore_errors=True)
os.makedirs(os.path.join(dst, "clusters_generated"))
header = "// Generated by rs-matter-codegen (update-rs-matter.sh). Do not edit.\n"
open(os.path.join(dst, "clusters_generated.rs"), "w").write(header + root)
for name in sorted(keep):
    shutil.copy(os.path.join(src, "clusters_generated", name + ".rs"),
                os.path.join(dst, "clusters_generated", name + ".rs"))
print(f"{len(keep)} of {len(found)} clusters")
